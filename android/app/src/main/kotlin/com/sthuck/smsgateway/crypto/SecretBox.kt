package com.sthuck.smsgateway.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Authenticated encryption helper for small sensitive payloads stored in
 * DataStore (e.g. Cloudflare Access headers).
 */
interface SecretBox {
    fun encrypt(plaintext: ByteArray): String
    fun decrypt(ciphertext: String): ByteArray?
    fun deleteKey()
}

/**
 * Android Keystore AES-256-GCM implementation of [SecretBox].
 *
 * Encodes ciphertext as `"v1:" + Base64Url.encode(iv12 + ciphertextAndTag)`.
 * The 12-byte IV is generated by Android Keystore on each encryption.
 */
@Singleton
class KeystoreSecretBox @Inject constructor() : SecretBox {

    override fun encrypt(plaintext: ByteArray): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        val iv = cipher.iv
        require(iv.size == IV_BYTES) { "Unexpected GCM IV length: ${iv.size}" }
        val ciphertextAndTag = cipher.doFinal(plaintext)
        return PREFIX_V1 + Base64Url.encode(iv + ciphertextAndTag)
    }

    override fun decrypt(ciphertext: String): ByteArray? {
        if (!ciphertext.startsWith(PREFIX_V1)) return null
        val encoded = ciphertext.removePrefix(PREFIX_V1)
        val combined = try {
            Base64Url.decode(encoded)
        } catch (_: Exception) {
            return null
        }
        if (combined.size < IV_BYTES + TAG_BYTES) return null
        val iv = combined.copyOfRange(0, IV_BYTES)
        val payload = combined.copyOfRange(IV_BYTES, combined.size)
        return try {
            val key = existingKey() ?: return null
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, iv))
            cipher.doFinal(payload)
        } catch (_: Exception) {
            null
        }
    }

    override fun deleteKey() {
        synchronized(this) {
            val ks = androidKeyStore()
            if (ks.containsAlias(ALIAS)) {
                ks.deleteEntry(ALIAS)
            }
        }
    }

    @Synchronized
    private fun getOrCreateKey(): SecretKey {
        existingKey()?.let { return it }
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        val spec = KeyGenParameterSpec.Builder(
            ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setKeySize(KEY_BITS)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setRandomizedEncryptionRequired(true)
            .setUserAuthenticationRequired(false)
            .build()
        generator.init(spec)
        return generator.generateKey()
    }

    private fun existingKey(): SecretKey? {
        val ks = androidKeyStore()
        if (!ks.containsAlias(ALIAS)) return null
        return ks.getKey(ALIAS, null) as? SecretKey
    }

    private fun androidKeyStore(): KeyStore =
        KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

    companion object {
        const val ALIAS = "sms_gateway_access_headers_aes256"
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val PREFIX_V1 = "v1:"
        private const val KEY_BITS = 256
        private const val IV_BYTES = 12
        private const val TAG_BYTES = 16
        private const val TAG_BITS = 128
    }
}
